// fisrt Function
$(document).ready(function () {
  let donations = $("#dona-types-container");
  donationsThings.forEach((thing) => {
    donations.append(
      `<div class="donation-type-cards">
    <a href="${thing.sticker.sourceUrl}" title="${thing.sticker.title}">
    <img
        src="${thing.sticker.imagePath}"
        alt="${thing.sticker.attribution.text}" created by ${thing.sticker.attribution.creator}- ${thing.sticker.attribution.provider}"
        /></a>
        <p>${thing.category}</p>
    <div>`,
    );
  });

  //gallery area

  const donationImgGallery = $("#masonry-gall-container");
  const slidesContainer = $("#custom-slides-container");
  let currentSlideIndex = 0;
  const totalSlides = galleryImgs.images.length;

  // 1. Injects items into Gallery Grid, Carousel Slides, and Dot Containers
  galleryImgs.images.forEach((image, index) => {
    // Append grid image card
    donationImgGallery.append(`
      <div class="masonry-item" data-index="${index}">
        <img src="${image.image_path}" alt="${image.alt}" id="${image.id}" />
        <div class="caption">${image.title}</div>
      </div>
    `);

    // Append corresponding carousel slide structure
    slidesContainer.append(`
      <div class="slide-item" data-slide-index="${index}">
        <img src="${image.image_path}" alt="${image.alt}">
        <div class="slide-details">
          <h3>${image.title}</h3>
          <p>${image.description}</p>
        </div>
      </div>
    `);

    // FIXED: Added class "dot-icon" and custom attribute tracking "data-index"
    $("#slides-rotate-container").append(
      `<div class="dot-icon" data-index="${index}"></div>`,
    );
  });

  // 2. Central State Engine
  function showSlide(index) {
    // Loop boundary wrappers
    if (index >= totalSlides) {
      currentSlideIndex = 0;
    } else if (index < 0) {
      currentSlideIndex = totalSlides - 1;
    } else {
      currentSlideIndex = index;
    }

    // Toggle active image visibility using basic string formatting attributes
    $(".slide-item").removeClass("active-slide");
    $(`.slide-item[data-slide-index="${currentSlideIndex}"]`).addClass(
      "active-slide",
    );

    // ADDED: Synchronize font-awesome active dot indicators
    $(".dot-icon").removeClass("active-dot");
    $(`.dot-icon[data-index="${currentSlideIndex}"]`).addClass("active-dot");
  }

  // 3. Grid Item Click -> Open Modal (Changed to document delegation for reliability)
  $(document).on("click", ".masonry-item", function () {
    const targetIndex = $(this).data("index");
    showSlide(targetIndex);
    $("#customGalleryModal").addClass("is-active");
  });

  // 4. ADDED: Click Indicators Functionality for the Balls
  $(document).on("click", ".dot-icon", function () {
    const targetIndex = $(this).data("index");
    showSlide(targetIndex);
  });

  // 5. ADDED: Global Keyboard Listener (Arrow Keys and Escape)
  $(document).on("keydown", function (e) {
    // Only intercepts keystrokes if your gallery overlay popup is open
    if ($("#customGalleryModal").hasClass("is-active")) {
      if (e.key === "ArrowRight" || e.key === "ArrowDown") {
        showSlide(currentSlideIndex + 1);
      } else if (e.key === "ArrowLeft" || e.key === "ArrowUp") {
        showSlide(currentSlideIndex - 1);
      } else if (e.key === "Escape") {
        $("#customGalleryModal").removeClass("is-active");
      }
    }
  });

  // 6. Manual Arrow Interactions
  $(".next-btn").on("click", function () {
    showSlide(currentSlideIndex + 1);
  });

  $(".prev-btn").on("click", function () {
    showSlide(currentSlideIndex - 1);
  });

  // 7. Close Modal Events (Clicking 'X' or dark backdrop overlay space)
  $(".close-btn, #customGalleryModal").on("click", function (e) {
    if (e.target === this || $(e.target).hasClass("close-btn")) {
      $("#customGalleryModal").removeClass("is-active");
    }
  });

  //nav bar responsiveness
  $(".nav-btn").click(function () {
    $("nav ul").stop().slideToggle(300);
  });

  $(window).resize(function () {
    if ($(window).width() > 768) {
      $("nav ul").removeAttr("style");
    }
  });

  //----------------------------------for faq part-------------------------------------------------//

  var htmlContent = "";
  $.each(data.faqs, function (index, item) {
    htmlContent += `<h3>${item.question}</h3>`;
    htmlContent += `<div><p>${item.answer}</p></div>`;
  });

  // write the HTML code inside our container element
  $("#faq-accordion").html(htmlContent);

  // turn it into accordian
  $("#faq-accordion").accordion({
    collapsible: true, // Allows an open section to close when clicked again
    active: false,
  });
});